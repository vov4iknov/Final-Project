user_states = {}

# функция с рандомным фактом
@bot.message_handler(commands=["fact"])
def send_fact(message):
    random_fact = random.choice(Facts)
    bot.reply_to(message, f"💀 Интересный факт:\n\n{random_fact}")

# функция с рандомным советом
@bot.message_handler(commands=["sovet"])
def send_sovet(message):
    random_sovet = random.choice(Sovets)
    bot.reply_to(message, f"🤔 Полезный совет:\n\n{random_sovet}")

# функция квиза
@bot.message_handler(commands=["quiz"])
def start_quiz(message):
    chat_id = message.chat.id
    # Начало: [индекс текущего вопроса, количество правильных ответов]
    user_states[chat_id] = [0, 0]
    bot.send_message(
        chat_id, "🌍 Начинаем квиз об экологии и изменении климата!"
    )

    # Отправляем первый вопрос
    bot.send_message(
        chat_id,
        f"❓ **Вопрос 1:** {Quiz[0]['q']}",
        parse_mode="Markdown",
    )


# Обрабатываем все текстовые ответы пользователя
@bot.message_handler(content_types=["text"])
def handle_text(message):
    chat_id = message.chat.id

    # Если пользователь пишет, но квиз не запущен
    if chat_id not in user_states:
        bot.send_message(
            chat_id, "Чтобы проверить свои знания о климате, напишите /quiz"
        )
        return

    # Получаем текущий шаг и счет пользователя
    current_step, score = user_states[chat_id]

    user_answer = message.text.strip().lower()
    correct_answer = str(Quiz[current_step]["a"]).lower()

    # Проверяем ответ текущего шага
    if user_answer in correct_answer:
        score += 1
        bot.send_message(message.chat.id, "✅ Абсолютно верно!")
    else:
        bot.send_message(
            chat_id,
            f"❌ К сожалению не верно :( \nПравильный ответ: *{Quiz[current_step]['a']}*",
            parse_mode="Markdown",
        )

    # Переходим к следующему вопросу
    current_step += 1

    # Проверяем, остались ли еще вопросы
    if current_step < len(Quiz):
        # Обновляем состояние и задаем следующий вопрос
        user_states[chat_id] = [current_step, score]
        bot.send_message(
            chat_id,
            f"❓ **Вопрос {current_step + 1}:** {Quiz[current_step]['q']}",
            parse_mode="Markdown",
        )
    else:
        # Финал квиза
        bot.send_message(
            chat_id,
            f"🏁 Наш мини-Квиз окончен!\nВы правильно ответили на {score} из {len(Quiz)} вопросов.\n\n"
            f"Каждый из этих фактов — напоминание о том, как важно беречь нашу планету. 🌱",
            parse_mode="Markdown",
        )
        # Стираем сессию из памяти
        del user_states[chat_id]


# Запуск бота
if __name__ == "__main__":
    bot.polling(non_stop=True)
